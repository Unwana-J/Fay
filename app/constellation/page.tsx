// ─── Utility: Blob to Base64 ────────────────────────────────────────────────
function blobToBase64(blob: Blob): Promise<string> {
  return new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.onloadend = () => resolve(reader.result as string);
    reader.onerror = reject;
    reader.readAsDataURL(blob);
  });
}

// ─── Similar Topics Recommendation Engine ─────────────────────────────────────
function getSimilarTopics(currentTopicId: string, category: string, currentTags: string[]) {
  const pool = TOPIC_BANK.filter((t) => t.id !== currentTopicId);
  const scored = pool.map((t) => {
    let score = 0;
    if (t.category === category) score += 10;
    if (t.tags && currentTags) {
      const intersect = t.tags.filter((tag) => currentTags.includes(tag));
      score += intersect.length * 3;
    }
    return { topic: t, score };
  });

  return scored
    .filter((item) => item.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, 3)
    .map((item) => item.topic);
}


const BASE_ORBIT_RADII = {
  sun: 125,
  moon: 225,
  star: 325,
};

interface OrbitBackdropData {
  sunRadii?: number[];
  moonRadii?: number[];
  starRadii?: number[];
  outerRimRadius?: number;
}

